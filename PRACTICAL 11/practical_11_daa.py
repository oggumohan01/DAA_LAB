# Floyd-Warshall Algorithm

INF = 99999

# Adjacency matrix representation of graph
graph = [
    [0,   5,  INF, 10],
    [INF, 0,   3,  INF],
    [INF, INF, 0,   1],
    [INF, INF, INF, 0]
]

V = len(graph)

# Floyd-Warshall Algorithm
dist = [row[:] for row in graph]

for k in range(V):
    for i in range(V):
        for j in range(V):
            if dist[i][k] != INF and dist[k][j] != INF:
                dist[i][j] = min(
                    dist[i][j],
                    dist[i][k] + dist[k][j]
                )

# Display shortest distance matrix
print("Shortest Distance Matrix:")

for i in range(V):
    for j in range(V):
        if dist[i][j] == INF:
            print("INF", end="\t")
        else:
            print(dist[i][j], end="\t")
    print()